            SourceProductionContext context,
            ISymbol symbol,
            string message)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                GeneratorDiagnostics.InvalidConfiguration,
                SymbolUtilities.GetLocation(symbol),
                message));
        }
